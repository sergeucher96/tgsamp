-- ============================================================
-- Удаляем черновые территории
--
-- Зоны 1…10 — это прямоугольники 400×400, которые были заглушкой.
-- Они не пригодны для игры:
--   * пересекались (Idlewood/Market, Idlewood/East Los Santos,
--     Idlewood/Marina) — 36% домов и бизнесов попадали сразу
--     в несколько зон, и подсчёт становился произвольным;
--   * покрывали не весь город — 90 объектов из 232 оставались
--     вне зон;
--   * Market и Los Santos Docks не содержали ни одного объекта,
--     то есть у aztec вообще не было бы территории.
--
-- Настоящие зоны рисуются на карте в RoadEditor (режим «Зона
-- войны»): двойной клик по вершинам, двойной клик по первой
-- вершине замыкает контур. Дальше геометрия настоящая, и
-- подсчёт домов/бизнесов по зонам даёт точные числа.
--
-- Зависимые таблицы удаляем ЯВНО, а не полагаемся на on delete
-- cascade. В наших миграциях каскад везде есть, но он проверен
-- по DDL-файлам, а не по живой базе. Явные delete работают
-- одинаково при каскаде и без него, и заодно показывают
-- в скрипте весь список затронутых таблиц.
--
-- Сами организации (grove/ballas/rifa/aztec) не трогаем:
-- они остаются, зоны просто создаются заново под них.
-- ============================================================

begin;

-- ------------------------------------------------------------
-- Зависимые таблицы. Порядок — от частого к главному.
-- territory_influence и territory_influence_actions удаляются
-- вместе с зонами каскадом, wars/war_events/war_participants
-- тоже завязаны на territory_id.
-- ------------------------------------------------------------
delete from territory_influence_actions;
delete from territory_influence;
delete from war_participants;
delete from war_events;
delete from wars;

-- ------------------------------------------------------------
-- Сами зоны, включая тестовую id=24 из RoadEditor
-- ------------------------------------------------------------
delete from territories;

commit;

