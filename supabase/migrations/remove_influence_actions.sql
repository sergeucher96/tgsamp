-- ============================================================
-- Миграция: удаление счётчика действий влияния
--
-- Таблица territory_influence_actions хранила счётчик действий
-- банды за скользящие сутки. По нему influenceService считал
-- убывающую отдачу: 1.0 → 0.8 → 0.6 → 0.4 → 0.2 → 0.1, чтобы
-- одна банда не могла захватить зону, просто часто нажимая кнопку.
--
-- Механизм мёртв: влияние писали в обход него напрямую —
-- warService.addInfluenceSafe при подведении итогов войны и
-- territoryDecay при затухании. А единственный вызов influenceService
-- шёл из captureTerritory — мгновенного захвата кнопкой, который
-- удалён вместе со старой системой захвата территорий.
--
-- Саму territory_influence НЕ трогаем: её по-прежнему читает и
-- пишет война. Убрано только то, что перестало использоваться.
-- Логику накопления влияния будем строить заново.
--
-- RLS-политики и индексы таблицы удаляются вместе с ней.
-- ============================================================

begin;

drop table if exists territory_influence_actions;

commit;

-- Просим PostgREST перечитать схему, иначе он продолжит
-- отдавать «Could not find the table» до ручного перезапуска.
notify pgrst, 'reload schema';
