-- ============================================================
-- Миграция: единое игровое время
--
-- Время суток должно совпадать у всех игроков, а часы на
-- устройстве у них разные: Москва, Алматы, Лос-Анджелес. Если
-- считать фазу от Date.now() в браузере, вечер для одного и
-- глубокая ночь для другого — и ночные скидки получат не те.
--
-- Поэтому единственный источник времени — база. Клиент при
-- запуске забирает now() и дальше считает сам, сверяясь с базой
-- раз в несколько минут: часы устройства могут враться, а таймер
-- в фоне — вставать.
--
-- Мгновенный снимок времени, а не now() внутри функции:
-- now() отдаёт время начала транзакции, а это значение и так
-- точное, когда функция вызвана напрямую.
--
-- Почему scale = 1 игровая минута за реальную секунду:
-- игровой день длится 24 реальные минуты, значит 1440 игровых
-- минут проходят за 1440 реальных секунд. Удобно считать, и при
-- такой скорости один игровой час равен одной реальной минуте.
--
-- Фазы: утро 5-11, день 11-19, ночь 19-5.
-- Отсчёт ведётся от полуночи по UTC, поэтому игровые часы
-- совпадают с часами UTC и не «плывут» при перезапуске сервера.
-- ============================================================

create or replace function game_server_now()
returns timestamptz
language sql
stable
as $$
  select now();
$$;

-- Функцию зовёт анонимный клиент из браузера: грант нужен
-- обязательно, без него PostgREST вернёт отказ до проверки
-- политик.
grant execute on function game_server_now() to anon, authenticated;

-- PostgREST кэширует список функций, поэтому без этого новая
-- функция не появится в API до перезапуска.
notify pgrst, 'reload schema';
